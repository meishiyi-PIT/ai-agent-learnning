import numpy as np
import torch

# ---------- demo 0：精度即显存，权重显存 = 参数个数 × 每参数字节数 ----------
GB = 1e9                                                     # 课件口径：1B 参数 = 10 亿个，1 GB = 10 亿字节
for fmt, nbytes in (("FP32", 4), ("FP16/BF16", 2), ("FP8/INT8", 1), ("INT4/NF4", 0.5)):
    print(f"{fmt:10s} {nbytes:>4} 字节/参数 | 8B 模型 {8e9 * nbytes / GB:>4.0f} GB | 72B 模型 {72e9 * nbytes / GB:>4.0f} GB")
print()

# ---------- demo 1：把 0.1 的 16 个比特拆成 符号 | 指数 | 尾数 ----------
x = 0.1
fp16_bits = int(np.float16(x).view(np.uint16))                                  # fp16 的 16 个比特，当成整数读出来
bf16_bits = torch.tensor(x, dtype=torch.bfloat16).view(torch.int16).item() & 0xFFFF   # bf16 同理（& 0xFFFF 去掉符号扩展）
for name, bits, exp_len in (("FP16", fp16_bits, 5), ("BF16", bf16_bits, 8)):
    s = f"{bits:016b}"                                                          # 转成 16 位二进制字符串
    print(f"{name}: 符号 {s[0]} | 指数 {s[1:1 + exp_len]} | 尾数 {s[1 + exp_len:]}")
