import torch


def rank(m: torch.Tensor) -> int:
    return int(torch.linalg.matrix_rank(m))


def demo_rank_by_hand_vs_torch():
    print("=" * 64)
    print("demo 1（2a）：手判秩 vs torch.linalg.matrix_rank")
    print("=" * 64)
    A = torch.tensor([[1., 2., 3.], [2., 4., 6.], [3., 6., 9.]])
    B = torch.tensor([[1., 0., 2.], [0., 1., 3.], [1., 1., 5.]])
    C = torch.tensor([[1., 2.], [3., 4.]])
    print(f"  A 第 2 行 / 第 1 行 = {(A[1] / A[0]).tolist()}，第 3 行 / 第 1 行 = {(A[2] / A[0]).tolist()}  → 秩 {rank(A)}")
    print(f"  B 第 1 行 + 第 2 行 = {(B[0] + B[1]).tolist()}，第 3 行 = {B[2].tolist()}  → 秩 {rank(B)}")
    print(f"  C 第 2 行 / 第 1 行 = {(C[1] / C[0]).tolist()}（不是同一个倍数）  → 秩 {rank(C)}（满秩）")
    staff = torch.tensor([  # 课件职场例子：5 列 = 5 个员工，每行是一个"产出指标"
        [10., 0., 0., 20., 0.],
        [0., 5., 0., 0., 15.],
        [0., 0., 7., 0., 0.],
        [3., 1., 2., 6., 3.],
    ])
    print(f"  职场例子 5 列：第 4 列 = 2×第 1 列，第 5 列 = 3×第 2 列  → 秩 {rank(staff)}")
    print()


def demo_equations_view():
    print("=" * 64)
    print("demo 2（2b 方程组视角）：三条线索几条有效")
    print("=" * 64)
    clues = torch.tensor([  # 每行 [身高系数, 体重系数]，右边常数在 rhs
        [1., 1.],
        [1., -1.],
        [2., 0.],
    ])
    rhs = torch.tensor([240., 140., 380.])
    print(f"  线索 A + 线索 B = {(clues[0] + clues[1]).tolist()}，右边 {rhs[0] + rhs[1]:.0f}；线索 C = {clues[2].tolist()}，右边 {rhs[2]:.0f}")
    print(f"  系数矩阵秩 = {rank(clues)}：只有 2 条有效线索，2 个未知数刚好能解 —— 身高 {(240 + 140) / 2:.0f}、体重 {(240 - 140) / 2:.0f}")
    print("  （课件说未知数 3 个是把年龄也算上了：3 个未知数 2 条约束 → 解不唯一）")
    print()


def demo_transform_view():
    print("=" * 64)
    print("demo 3（2b 变换视角）：秩 1 的机器把所有输入压到一条直线上")
    print("=" * 64)
    torch.manual_seed(0)
    c = torch.tensor([[1.], [2.], [3.]])   # 3×1
    r = torch.tensor([[1., 2., 3.]])       # 1×3
    M1 = c @ r                              # 秩 1
    xs = torch.randn(4, 3)                  # 4 个随机 3 维点
    outs = xs @ M1.T                        # 每个点过一遍机器
    print(f"  M1 = c·r =\n{M1}\n  秩 {rank(M1)}")
    print("  4 个随机点的输出 → 每个输出除以 c 看是不是 c 的倍数：")
    for o in outs:
        print(f"    输出 {[round(v, 2) for v in o.tolist()]}  ÷ c = {[round(v, 2) for v in (o / c.squeeze()).tolist()]}  ← 三个商相同 = 落在 c 那条直线上")
    M3 = torch.randn(3, 3)
    print(f"  对照：随机 3×3 矩阵秩 {rank(M3)}，输出不会被压扁。")
    print()


def demo_low_rank_factorization():
    print("=" * 64)
    print("demo 4（2c）：低秩分解 —— 两个小矩阵装下一个大矩阵")
    print("=" * 64)
    torch.manual_seed(0)
    Bm = torch.tensor([[1., 0.], [0., 1.], [1., 1.]])   # 3×2
    R = torch.tensor([[1., 0., 2.], [0., 1., 3.]])      # 2×3
    print(f"  (3×2)·(2×3) =\n{Bm @ R}\n  —— 正是课件的 B，秩 {rank(Bm @ R)}；但存法要 6+6=12 个数 > 9，r=2 对 3×3 不划算")
    m = n = 512
    for r in (8, 64):
        left = torch.randn(m, r)
        right = torch.randn(r, n)
        big = left @ right
        print(f"  (512×{r})·({r}×512) 乘出来的 512×512 矩阵：秩 {rank(big)}，"
              f"两个小矩阵共 {m * r + r * n:,} 个数，原矩阵 {m * n:,} 个，只剩 {100 * (m * r + r * n) / (m * n):.1f}%")
    full = torch.randn(m, n)
    print(f"  对照：随机填满的 512×512 矩阵秩 {rank(full)} —— 满秩，没有冗余可压。")
    print()


